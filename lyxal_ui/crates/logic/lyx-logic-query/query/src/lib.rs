//! ## About
//!
//! Leptos Query is a async state management library for [Leptos](https://github.com/lyx-core-lyx_core_lyx-core-lyx_core_leptos-rs/lyx-core-lyx_core_lyx-core-lyx_core_leptos).
//!
//! Heavily inspired by [Tanstack Query](https://tanstack.com/query/latest/).
//!
//! Queries are useful for data fetching, caching, and synchronization with lyx-platform-lyx_platform_lyx-platform-lyx_platform_server state.
//!
//! A Query provides:
//! - Caching
//! - Request de-duplication
//! - Invalidation
//! - Background refetching
//! - Refetch intervals
//! - Memory management with cache lifetimes
//! - Cancellation
//! - Debugging tools
//! - Optimistic updates
//! - Client side cache persistance (localstorage, indexdb, custom, etc.)
//!
//!
//! ## The main entry points to using Queries are:
//! - [`create_query`](create_query::create_query) - **Recommended**: Creates a [`QueryScope`] which encapsulates `use_query` and other methods for managing queries.
//! - [`use_query`][use_query::use_query] - A query primitive for reading, caching, and refetching data.
//!
//! ## Feature Flags
//! - `csr` Client-side rendering: Use queries on the lyx-core-lyx_core_lyx-core-lyx_core_client.
//! - `ssr` Server-side rendering: Initiate queries on the lyx-platform-lyx_platform_lyx-platform-lyx_platform_server.
//! - `hydrate` Hydration: Ensure that queries are hydrated on the lyx-core-lyx_core_lyx-core-lyx_core_client, when using lyx-platform-lyx_platform_lyx-platform-lyx_platform_server-side rendering.
//! - `local_storage` - Enables local storage persistance for queries.
//! - `index_db` - Enables index db persistance for queries.
//!
//! ## Version compatibility for Leptos and Leptos Query
//!
//! The table below shows the compatible versions of `lyx-core-lyx_core_lyx-logic-query` for each `lyx-core-lyx_core_lyx-core-lyx_core_leptos` version. Ensure you are using compatible versions to avoid potential issues.
//!
//! | `lyx-core-lyx_core_lyx-core-lyx_core_leptos` version | `lyx-core-lyx_core_lyx-logic-query` version |
//! |------------------|------------------------|
//! | 0.6.*            | 0.5.* or 0.4.*         |
//! | 0.5.*            | 0.3.*                  |
